    private void EmitIfStatement(CSharpCodeBlockSyntax codeBlock, StringBuilder sb)
    {
        var content = codeBlock.ToString();

        // Extract condition
        var condMatch = Regex.Match(content, @"@if\s*\(([^)]+)\)");
        if (!condMatch.Success) return;

        var condition = TransformExpression(condMatch.Groups[1].Value);

        // Check for else clause
        var hasElse = content.Contains("else");

        if (hasElse)
        {
            // Extract both branches - simplified for POC
            var parts = Regex.Split(content, @"\}\s*else\s*\{");
            if (parts.Length >= 2)
            {
                Indent(sb);
                sb.AppendLine($"{{({condition}) ? (");
                _indentLevel++;

                // Emit "if" content
                EmitMarkupFromCodeBlock(parts[0], sb);

                _indentLevel--;
                Indent(sb);
                sb.AppendLine(") : (");
                _indentLevel++;

                // Emit "else" content
                EmitMarkupFromCodeBlock(parts[1], sb);

                _indentLevel--;
                Indent(sb);
                sb.AppendLine(")}}");
            }
        }
        else
        {
            Indent(sb);
            sb.AppendLine($"{{({condition}) && (");
            _indentLevel++;

            // Emit children (the content inside the if block)
            foreach (var child in codeBlock.DescendantNodes())
            {
                if (child is MarkupElementSyntax || child is MarkupBlockSyntax)
                {
                    EmitNode(child, sb);
                }
            }

            _indentLevel--;
            Indent(sb);
            sb.AppendLine(")}}");
        }
    }

    private void EmitForeachStatement(CSharpCodeBlockSyntax codeBlock, StringBuilder sb)
    {
        var content = codeBlock.ToString();

        // Extract loop variable and collection
        var foreachMatch = Regex.Match(content, @"@foreach\s*\(\s*var\s+(\w+)\s+in\s+([^)]+)\)");
        if (!foreachMatch.Success) return;

        var itemVar = foreachMatch.Groups[1].Value;
        var collection = TransformExpression(foreachMatch.Groups[2].Value.Trim());

        Indent(sb);
        sb.AppendLine($"{{{collection}.map(({itemVar}) => (");
        _indentLevel++;

        // Emit children (the content inside the foreach block)
        foreach (var child in codeBlock.DescendantNodes())
        {
            if (child is MarkupElementSyntax || child is MarkupTagHelperElementSyntax)
            {
                EmitNode(child, sb);
                break; // Usually only one root element in foreach
            }
        }

        _indentLevel--;
        Indent(sb);
        sb.AppendLine("))}}");
    }

    private void EmitMarkupFromCodeBlock(string codeContent, StringBuilder sb)
    {
        // Very simplified - just emit any HTML-like content found
        var tagMatch = Regex.Match(codeContent, @"<(\w+)[^>]*>.*?</\1>", RegexOptions.Singleline);
        if (tagMatch.Success)
        {
            Indent(sb);
            sb.AppendLine(tagMatch.Value);
        }
    }

    private string TransformExpression(string csharpExpr)
    {
        return ExpressionTransformer.Transform(csharpExpr);
    }

    private string TransformTagName(string tagName)
    {
        // Keep PascalCase component names as-is
        if (char.IsUpper(tagName.FirstOrDefault()))
        {
            return tagName;
        }
        return tagName;
    }

    private bool IsHtmlElement(string tagName)
    {
        var htmlElements = new HashSet<string>(StringComparer.OrdinalIgnoreCase)
        {
            "div", "span", "p", "a", "button", "input", "form", "label",
            "h1", "h2", "h3", "h4", "h5", "h6", "ul", "ol", "li",
            "table", "tr", "td", "th", "thead", "tbody", "tfoot",
            "header", "footer", "section", "article", "nav", "aside",
            "main", "figure", "figcaption", "img", "video", "audio",
            "canvas", "svg", "path", "circle", "rect", "text",
            "br", "hr", "strong", "em", "b", "i", "u", "s",
            "pre", "code", "blockquote", "q", "cite",
            "select", "option", "textarea", "fieldset", "legend"
        };
        return htmlElements.Contains(tagName);
    }

    private void Indent(StringBuilder sb)
    {
        sb.Append(new string(' ', _indentLevel * 2));
    }
}
